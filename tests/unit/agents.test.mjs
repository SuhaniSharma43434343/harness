import { test } from 'node:test';
import assert from 'node:assert/strict';
import { cpSync, existsSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {
  AGENTS_DIR,
  AGENT_IDS,
  agentsForPhase,
  assertAgentForPhase,
  checkGenerated,
  generatedFiles,
  loadAgents,
  parseAgent,
  writeGenerated,
} from '../../src/core/agents.mjs';
import { PermissionDenied, SchemaInvalid } from '../../src/core/errors.mjs';
import { PHASES } from '../../src/core/project.mjs';

const agents = loadAgents();

test('there is one definition for each of the 8 agent roles in the task contract', () => {
  assert.equal(AGENT_IDS.length, 8);
  assert.deepEqual(agents.map((a) => a.id).sort(), [...AGENT_IDS].sort());
});

test('the committed Claude Code and Cursor files match agents/', () => {
  assert.deepEqual(checkGenerated(agents), [], 'run forge agents generate');
});

test('the router picks the agents that work in each phase', () => {
  assert.deepEqual(agentsForPhase('CREATED', agents), []);
  assert.deepEqual(agentsForPhase('INTAKE', agents), ['project-manager']);
  assert.deepEqual(agentsForPhase('BUILD', agents), ['builder']);
  assert.deepEqual(agentsForPhase('REPAIR', agents), ['builder', 'qa-verifier']);
  assert.deepEqual(agentsForPhase('PRODUCTION_DEPLOY', agents), ['lead-developer']);
  for (const p of PHASES.slice(1)) assert.ok(agentsForPhase(p.name, agents).length, `${p.name} has no agent`);
  assert.throws(() => agentsForPhase('SHIPPING', agents), SchemaInvalid);
});

test('an agent outside its phases is refused with the agents that are allowed', () => {
  assert.equal(assertAgentForPhase('BUILD', 'builder', agents), true);
  assert.throws(
    () => assertAgentForPhase('INTAKE', 'builder', agents),
    (e) => e instanceof PermissionDenied && /project-manager/.test(e.hint),
  );
});

test('generated files keep the source instructions and mark themselves as generated', () => {
  const files = generatedFiles(agents);
  assert.equal(Object.keys(files).length, 16);
  for (const a of agents) {
    for (const rel of [`.claude/agents/${a.id}.md`, `.cursor/rules/${a.id}.mdc`]) {
      const text = files[rel];
      assert.ok(text.includes(a.body.trim()), `${rel} lost its instructions`);
      assert.ok(text.includes(`from agents/${a.id}.md`), `${rel} has no banner`);
      const description = text.match(/^description: (.*)$/m)[1];
      assert.doesNotThrow(() => JSON.parse(description), `${rel} description must be a quoted YAML string`);
    }
  }
  assert.match(files['.claude/agents/builder.md'], /^tools: Read, Write, Edit, Glob, Grep, Bash$/m);
  assert.match(files['.cursor/rules/content-ux.mdc'], /^globs: workspace\/\*\/ux\/\*\*,workspace\/\*\/content\/\*\*$/m);
  assert.match(files['.claude/agents/builder.md'], /owns_files/);
});

test('check reports edited and missing files; generate repairs them and removes stale ones', () => {
  const root = mkdtempSync(join(tmpdir(), 'forge-agents-'));
  writeGenerated(agents, root);
  assert.deepEqual(checkGenerated(agents, root), []);

  writeFileSync(join(root, '.claude/agents/builder.md'), 'hand edited');
  writeFileSync(join(root, '.cursor/rules/old-role.mdc'), '<!-- Generated by forge agents generate from agents/old-role.md. -->');
  writeFileSync(join(root, '.cursor/rules/team-notes.mdc'), 'not generated');
  const drift = checkGenerated(agents, root);
  assert.deepEqual(drift, [{ file: '.claude/agents/builder.md', problem: 'differs from its source' }]);

  writeGenerated(agents, root);
  assert.deepEqual(checkGenerated(agents, root), []);
  assert.equal(existsSync(join(root, '.cursor/rules/old-role.mdc')), false, 'stale generated file removed');
  assert.equal(existsSync(join(root, '.cursor/rules/team-notes.mdc')), true, 'hand-written rules are kept');
});

test('bad agent definitions are rejected with the reason', () => {
  assert.throws(() => parseAgent('# no frontmatter'), /no frontmatter/);
  assert.throws(() => parseAgent('---\nid: x\nmood: happy\n---\nbody'), /unknown field "mood"/);
  assert.throws(() => parseAgent('---\nid: x\nname: X\ndescription: d\nphases: BUILD\nwrites: []\ntools: []\n---\nbody'), /must be a list/);
  assert.throws(() => parseAgent('---\nid: x\n---\nbody'), /missing field "name"/);

  const dir = mkdtempSync(join(tmpdir(), 'forge-agents-src-'));
  cpSync(AGENTS_DIR, dir, { recursive: true });
  const file = join(dir, 'builder.md');
  writeFileSync(file, readFileSync(file, 'utf8').replace('phases: [BUILD, REPAIR]', 'phases: [BUILD, PARTY]'));
  assert.throws(() => loadAgents(dir), (e) => e instanceof SchemaInvalid && e.details.includes('unknown phase PARTY'));

  const dir2 = mkdtempSync(join(tmpdir(), 'forge-agents-src-'));
  cpSync(AGENTS_DIR, dir2, { recursive: true });
  writeFileSync(join(dir2, 'qa-verifier.md'), readFileSync(join(dir2, 'qa-verifier.md'), 'utf8').replace('id: qa-verifier', 'id: tester'));
  assert.throws(() => loadAgents(dir2), SchemaInvalid);
});
