import { appendFileSync, copyFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { createServer } from 'node:http';
import { dirname, join } from 'node:path';
import { Readable } from 'node:stream';
import { fileURLToPath } from 'node:url';
import { ConfigMissing, SchemaInvalid } from '../../src/core/errors.mjs';
import { createHandler } from './handler.mjs';

// Working forms (Release 1.0): the built site posts each form to a Vercel function at
// /api/form?form=<id>, which checks the submission again on the server, rate limits it and
// forwards it to the operator's webhook (FORM_WEBHOOK_URL, set on the Vercel project). The
// same handler runs locally as startLocalEndpoint, which writes submissions to a file instead,
// for previews and the forms gate.

export const actionKinds = { install: 'write', startLocalEndpoint: 'write', actionFor: 'read' };
export const configSchema = {
  type: 'object',
  properties: { FORM_WEBHOOK_URL: { type: 'string', pattern: '^https://' } },
};

const HANDLER = join(dirname(fileURLToPath(import.meta.url)), 'handler.mjs');

export async function healthCheck(ctx) {
  if (!ctx.env.FORM_WEBHOOK_URL) {
    return { ok: false, detail: 'FORM_WEBHOOK_URL is not set, so submissions would have nowhere to go' };
  }
  return { ok: true, detail: `forwards to ${new URL(ctx.env.FORM_WEBHOOK_URL).host}` };
}

// The URL a form's `action` attribute should use.
export function actionFor(id) {
  return `/api/form?form=${encodeURIComponent(id)}`;
}

function checkForms(forms) {
  if (!forms || typeof forms !== 'object' || !Object.keys(forms).length) {
    throw new ConfigMissing('No forms to install', { hint: 'Pass the forms from the site’s site.json.' });
  }
  for (const [id, f] of Object.entries(forms)) {
    if (!/^[a-z0-9][a-z0-9-]*$/.test(id) || !Array.isArray(f?.fields) || !f.fields.every((x) => typeof x?.name === 'string')) {
      throw new SchemaInvalid(`Form "${id}" needs an id like "contact" and a list of fields with names`);
    }
  }
  // Only what the server needs: field names, types, whether they are required.
  return Object.fromEntries(
    Object.entries(forms).map(([id, f]) => [id, { fields: f.fields.map(({ name, type, required, maxLength }) => ({ name, type, required: Boolean(required), maxLength })) }]),
  );
}

// Writes the function into the built site's api/ folder, which Vercel deploys as a function.
// Files starting with _ are helpers, not endpoints, and api/ is never served as static files.
export function install(distDir, { forms }) {
  const spec = checkForms(forms);
  const api = join(distDir, 'api');
  mkdirSync(api, { recursive: true });
  copyFileSync(HANDLER, join(api, '_forge-form-handler.mjs'));
  writeFileSync(join(api, '_forge-forms.mjs'), `// Generated by the form-function plugin.\nexport default ${JSON.stringify(spec, null, 2)};\n`);
  writeFileSync(
    join(api, 'form.mjs'),
    [
      '// Generated by the form-function plugin. Submissions go to FORM_WEBHOOK_URL.',
      "import { createHandler, webhookForwarder } from './_forge-form-handler.mjs';",
      "import forms from './_forge-forms.mjs';",
      '',
      'const handle = createHandler({ forms, forward: webhookForwarder(process.env.FORM_WEBHOOK_URL) });',
      '',
      'export function POST(request) {',
      '  return handle(request);',
      '}',
      '',
      'export function GET(request) {',
      '  return handle(request);',
      '}',
      '',
    ].join('\n'),
  );
  return { files: ['api/form.mjs', 'api/_forge-form-handler.mjs', 'api/_forge-forms.mjs'], actions: Object.fromEntries(Object.keys(spec).map((id) => [id, actionFor(id)])) };
}

// A local endpoint with the same checks. Each accepted submission is appended to `file` as one
// JSON line, so QA can read what would have been sent.
export function startLocalEndpoint({ forms, file, port = 0, rateLimit }) {
  const spec = checkForms(forms);
  mkdirSync(dirname(file), { recursive: true });
  if (!existsSync(file)) writeFileSync(file, '');
  const handle = createHandler({ forms: spec, rateLimit, forward: async (payload) => appendFileSync(file, JSON.stringify(payload) + '\n') });

  const server = createServer(async (req, res) => {
    const url = `http://127.0.0.1${req.url}`;
    if (!new URL(url).pathname.startsWith('/api/form')) {
      res.writeHead(404).end();
      return;
    }
    const init = { method: req.method, headers: { ...req.headers, 'x-forwarded-for': req.socket.remoteAddress } };
    if (req.method !== 'GET' && req.method !== 'HEAD') Object.assign(init, { body: Readable.toWeb(req), duplex: 'half' });
    const response = await handle(new Request(url, init));
    res.writeHead(response.status, Object.fromEntries(response.headers));
    res.end(Buffer.from(await response.arrayBuffer()));
  });
  return new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(port, '127.0.0.1', () => {
      resolve({ url: `http://127.0.0.1:${server.address().port}/api/form`, close: () => new Promise((r) => server.close(() => r())) });
    });
  });
}

